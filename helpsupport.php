        <div class="text-left">
            <h2 id="num1">1. What is the Online Vehicle Identification System (OVITS)?</h2>
            <p>The Online Vehicle Identification and Tracking System (OVITS) is a program designed to manage and monitor vehicles owned by students on campus. Its primary goal is to ensure a smooth and secure flow of traffic in and out of the school premises. The system allows campus authorities to effectively monitor vehicle movement, minimize unauthorized access, and create a safer environment for everyone. Students register their vehicles through OVITS, and a unique sticker is issued for identification purposes. This sticker includes a control number and a QR code or barcode that guards scan at the entrance for verification.</p>
            <h2 id="num3">3. What are the fees for the UMak vehicle sticker?</h2>
            <p>The vehicle sticker costs Php 200.00 for one year. This fee applies to four-wheeled vehicles, motorcycles, and e-bikes.</p>
            <h2 id="num5">5. What happens if I violate parking rules?</h2>
            <p>Violations of parking policies will result in the following sanctions:<br><br>
                5.1 First offense: Warning and written reprimand.<br>
                5.2 Second offense: Revocation of parking privileges or a fine of Php 3,000.00.
                </p>
            <h2 id="num7">7. Are there priority parking slots available?</h2>
            <p>Yes, the following individuals are given priority for designated parking slots:<br><br>
                7.1 Permanently or physically challenged individuals.<br>
                7.2 Pregnant women.<br>
                7.3 Senior citizens.</p>
            <h2 id="num9">9. What are the rules for overnight parking?</h2>
            <p>Overnight parking is generally not allowed unless pre-approved. Fees for overnight parking are:<br><br>
                9.1 Php 2,500.00 per month.<br>
                9.2 Php 300.00 per night.
                Overnight parking is permitted only from 10:00 PM to 5:00 AM, Monday to Friday.
                </p>
        </div>
        <div class="text-right">
            <h2 id="num2">2. How do I apply for a vehicle sticker?</h2>
            <p>2.1  To apply for a vehicle sticker, follow these steps:<br>
                2.2 Complete the "Application for Vehicle Sticker" form. Provide your personal details, vehicle information, and contact information.<br>
                2.3 Attach the required documents:<br>
                2.4 Photocopy of the Vehicle Certificate (and Deed of Sale if the vehicle is not registered under your name).<br>
                2.5 Photocopy of the Official Receipt of Vehicle Registration (latest).<br>
                2.6 Photocopy of a valid driver’s license.<br>
                2.7 Photocopy of your UMak employee or student ID.<br>
                2.8 Official receipt of vehicle sticker payment.<br>
                2.9 Submit the form and requirements to the Occupational Health and Safety Office (OHSO).<br>
                </p>
            <h2 id="num4">4. Where should the sticker be placed on the vehicle?</h2>
            <p>The UMak vehicle sticker must be placed on:<br>
                4.1 The upper left side of the front windshield for four-wheeled vehicles.<br>
                4.2 The front area of motorcycles and e-bikes for easy visibility by the guards.<br>
                </p>
            <h2 id="num6">6. Are parking privileges transferable?</h2>
            <p>No, parking privileges are non-transferable and are valid only while the employee or student remains connected to the university.</p>
            <h2 id="num8">8. What should I do if my vehicle needs maintenance or repair on campus?</h2>
            <p>Vehicle maintenance or repair on campus is not allowed unless it is due to a mechanical failure. In such cases, secure a permit immediately from the university authorities.</p>
            <h2 id="num10">10. Who can I contact for further assistance?</h2>
            <p>For further assistance or inquiries regarding OVITS and parking policies, you may contact the Occupational Health and Safety Office (OHSO).</p>
