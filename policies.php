                <h2>Implementing Rules and Regulation (IRR) of BOR Resolution 2023-203 Entry/Parking Policy at the University of Makati</h2>
            </div>

            <div class="text"> 
                <p>All UMak employees and students, who will enter and park in the university with a personal vehicle shall secure a sticker application form, which must be filed at the Occupational Health and Safety Office (OHSO). Stickers are for identification purposes, and parking is on a “first come, first serve basis”. For students limited parking slots are available. The sticker costs are Php 200.00 pesos for four-wheeled vehicles, motorcycles, and electronic bikes, which is good for one year;</p>
                <p>1.1 The UMak Car Sticker is always required for entry and parking at the campus premises.</p>
                <p>1.2 The UMak Car Sticker is issued on a per-year basis and shall expire after the completion of the issuance of car stickers for the following year or as announced by the OHSO.</p>
                <p>1.3 The UMak Car Sticker will be considered valid only when they are properly displayed on the upper left side of the vehicle’s front windshield so that they are readable from the outside. On motorcycles and e-bikes, the sticker should be placed in front for full view of the guards at the entrance gate.</p>
                <p>1.4 The registrant or requesting party is held responsible for any violation involving the registered vehicle when he/she is operating the vehicle or when the vehicle is being used by another individual.</p>
                <p>1.5 Only valid UMak Car Stickers shall be displayed on the vehicle.</p>
                <p>1.6 The Car Sticker privilege holders shall take full responsibility for informing or reminding their drivers and immediate family members of the Traffic and Parking Regulations of the University. The privilege holders shall be held responsible for violations, damages, and injuries committed by their drivers, employees, and immediate family members.</p>
                <p>Parking privileges are non-transferable and valid only as long as the employee and student are presently connected to the university;
                    The parking slot for guests, visitors, or clients who have business or transactions in the university will be provided a parking space within the university premises;
                    Permanently or physically challenged (handicapped) employees, guests or visitors, pregnant women, and senior citizens shall be given priority to park their vehicles at the designated area;</p>
                <p>a. Those who intend to park at the university must observe the following:a. Littering is not allowed.</p>
                <p>b. Drivers must respect others’ property.</p>
                <p>c. Drivers should not turn carelessly or drive irresponsibly.</p>
                <p>d. Drivers must observe the required speed limit (10kph).</p>
                <p>e. Idling while waiting is not allowed.</p>
                <p>f. Vehicles are not allowed to block front or back entrances, park at spaces reserved for individuals as mentioned above.</p>
                <p>g. Obstruct loading/unloading of university vehicles.</p>
                <p>h. Reserved parking spaces for government vehicles and school officials must be observed.</p>
                <p>Parking spaces are not permanent benefits hence overnight parking is not allowed except when the owner of the vehicle signifies his/her intention to pay an overnight parking fee of Php 2,500.00 pesos per month or Php 300.00 pesos per night for the vehicle. Overnight parking starts from 10:00 PM to 5:00 AM, Monday to Friday only, and applicants are subject to pre-qualifications;</p>

                <p>Overnight parking exemptions are as follows:</p>
                <p>a. Employees with out-of-town seminars and training with ManCom approval and approved Official Business (OB) Form from immediate supervisor.</p>
                <p>b. Employee vehicle with mechanical failure while being parked inside university premises.</p>
                <p>c. Government-marked vehicle.</p>
                <p>d. UMak ManCom</p>

                <p>Vehicles left unattended for more than 48 hours without any permit, whatsoever, will be clamped and the owner will have to pay the storage fee and the removal fees;
                    Owners of vehicles should not conduct maintenance or repair jobs to their cars while they are parked in the university, except when a mechanical failure occurs. A permit in such case must be secured immediately.
                    The university will not assume any liability for theft, vandalism, fire, damage, or any similar incident to any personal vehicle that is parked on the university premises;
                    Any employee who is found parking in an authorized or prohibited area or another manner disregarding this policy will be subject to the following sanctions:</p>

                <p>a. First offense – warning and a written reprimand</p>
                <p>b. Second offense – revocation of the parking privileges or a fine of Php 3,000.00 pesos.</p>      
                
                <p>The university gate will be closed from 10:00 PM till 5:00 AM. Vehicles will only be allowed to enter and exit the university with proper clearance and coordination with the Security office.</p>
